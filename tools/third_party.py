#!/usr/bin/env python3
"""Writes THIRD-PARTY.md: the crates built into the inkdot program for the handheld (nibOS with
DSlot's part, and the stock OS), each with its licence, then the licence and copyright texts the
crates ship, which go with every copy of the program.

    python3 tools/third_party.py > THIRD-PARTY.md

Reads `cargo metadata --locked` for the handheld's target; the crates' own texts come from
Cargo's sources (`cargo fetch --locked` first if one is missing).
"""

import json
import subprocess
import sys
from pathlib import Path

TARGET = "aarch64-unknown-linux-gnu"
BUILDS = {"nibos": ["--features", "dslot"], "stock": ["--no-default-features", "--features", "stock"]}
TEXTS = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "COPYRIGHT", "UNLICENSE")


def packages(args):
    """The crates the program depends on in one build, without the workspace's own."""
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1", "--manifest-path",
         "crates/inkdot/Cargo.toml", "--filter-platform", TARGET, *args],
        check=True, capture_output=True, text=True).stdout)
    # What the program reaches, from its own node: a workspace crate the build leaves out
    # (an optional dependency off in this build) and its dependencies are not in it.
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    ours = set(meta["workspace_members"])
    used, todo = set(), [meta["resolve"]["root"]]
    while todo:
        node = todo.pop()
        if node in used:
            continue
        used.add(node)
        todo.extend(d["pkg"] for d in nodes[node]["deps"])
    return [p for p in meta["packages"] if p["id"] in used and p["id"] not in ours]


def texts(package):
    """The licence and notice files beside a crate's Cargo.toml, by name."""
    here = Path(package["manifest_path"]).parent
    found = {}
    for f in sorted(here.iterdir()):
        if f.is_file() and f.name.upper().startswith(TEXTS):
            found[f.name] = f.read_text(errors="replace").strip()
    named = package.get("license_file")
    if named and (here / named).is_file():
        found.setdefault(Path(named).name, (here / named).read_text(errors="replace").strip())
    return sorted(found.items())


def main():
    crates, builds = {}, {}
    for build, args in BUILDS.items():
        for p in packages(args):
            crates[p["id"]] = p
            builds.setdefault(p["id"], []).append(build)
    rows = sorted(crates.values(), key=lambda p: (p["name"], p["version"]))

    w = sys.stdout.write
    w("# Third-party notices\n\n"
      "inkdot is MIT OR Apache-2.0 (LICENSE-MIT, LICENSE-APACHE). Built into the program are\n"
      "the crates below, each under its own licence; their licence and copyright texts follow\n"
      "the list. Generated by `tools/third_party.py`; do not edit.\n\n"
      "Also in the program, through nibkit: Roboto Condensed, under the SIL Open Font License\n"
      "1.1 (LICENSE-OFL); and, for RetroAchievements, rcheevos 12.4.0 (MIT, vendored in\n"
      "nibkit's nib-cheevos/rcheevos with its LICENSE), which is C, not a crate, so it is not\n"
      "in the list below. SDL2 is not built in: the program links to the system's SDL2 (zlib\n"
      "licence).\n\n"
      "| Crate | Version | Licence | Built for |\n|---|---|---|---|\n")
    for p in rows:
        licence = p["license"] or f"see {p.get('license_file')}"
        w(f"| {p['name']} | {p['version']} | {licence} | {', '.join(builds[p['id']])} |\n")

    # The many identical copies (MIT, Apache-2.0) are printed once, under every crate with one.
    by_text = {}
    for p in rows:
        for name, body in texts(p):
            by_text.setdefault(body, []).append(f"{p['name']} {p['version']} ({name})")
    w("\n## Licence and copyright texts\n")
    for body, owners in by_text.items():
        w("\n### " + "; ".join(owners) + "\n\n```\n" + body + "\n```\n")
    bare = [p for p in rows if not texts(p)]
    if bare:
        w("\n## Crates that ship no licence file\n\n")
        for p in bare:
            where = f", {p['repository']}" if p.get("repository") else ""
            w(f"- {p['name']} {p['version']}: {p['license']}{where}\n")


if __name__ == "__main__":
    main()
