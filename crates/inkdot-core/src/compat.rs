#[cfg(test)]
mod tests {
    use super::*;
    use crate::cart::Header;

    fn header(title: &[u8], licensee: u8) -> Header {
        let mut rom = [0u8; 0x150];
        rom[0x134..0x134 + title.len()].copy_from_slice(title);
        rom[0x14b] = licensee;
        Header::parse(&rom)
    }

    #[test]
    fn unlicensed_games_get_the_default() {
        assert_eq!(for_header(&header(b"DMG-ACID2", 0x00)), DEFAULT);
    }

    #[test]
    fn a_shared_checksum_is_told_apart_by_the_fourth_letter() {
        // Find a checksum listed twice with different letters, and check each letter.
        let (hash, a, pa) = BY_TITLE.iter().find(|(_, l, _)| *l != 0).copied().unwrap();
        let mut title = [b' '; 16];
        title[3] = a;
        // Adjust the first byte so the bytes sum to `hash`.
        let rest = title[1..].iter().fold(0u8, |s, b| s.wrapping_add(*b));
        title[0] = hash.wrapping_sub(rest);
        assert_eq!(for_header(&header(&title, 0x01)), pa);
        title[3] = a.wrapping_add(1);
        title[0] = hash.wrapping_sub(title[1..].iter().fold(0u8, |s, b| s.wrapping_add(*b)));
        let other = BY_TITLE
            .iter()
            .find(|(h, l, _)| *h == hash && (*l == 0 || *l == title[3]));
        assert_eq!(
            for_header(&header(&title, 0x01)),
            other.map_or(DEFAULT, |e| e.2)
        );
    }
}
