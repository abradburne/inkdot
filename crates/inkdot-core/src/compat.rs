//! The palettes a CGB gives games made for the DMG.
//!
//! The CGB's boot ROM colours a DMG game by its title: for a game whose header names Nintendo
//! as the licensee, it sums the 16 title bytes and looks the sum up in a table (some sums are
//! shared, and then the title's fourth letter decides); every other game gets the default.
//! The result is three palettes, for the background and the two object palettes, which
//! BGP/OBP0/OBP1 then index. The player could also pick one of twelve by holding a direction
//! (and A or B) during the boot animation; those are offered as presets.
//!
//! Sources: Pan Docs "Power Up Sequence", "Compatibility palettes" (the algorithm); The Cutting
//! Room Floor, "Notes:Game Boy Color Bootstrap ROM" (the tables, as 24-bit colours made from
//! the 15-bit ones with `(c << 3) | (c >> 2)`; converted back here with `c >> 3`).

use crate::cart::Header;

/// Three RGB555 palettes of four colours: background, object 0, object 1.
pub type Palettes = [[u16; 4]; 3];

/// The palettes for games not in the table.
pub const DEFAULT: Palettes = [
    [0x7fff, 0x1bef, 0x6180, 0x0000],
    [0x7fff, 0x421f, 0x1cf2, 0x0000],
    [0x7fff, 0x421f, 0x1cf2, 0x0000],
];

/// The palettes the boot ROM picks for a DMG game with this header.
pub fn for_header(header: &Header) -> Palettes {
    if !header.licensed_by_nintendo() {
        return DEFAULT;
    }
    let sum = header
        .title_bytes
        .iter()
        .fold(0u8, |s, b| s.wrapping_add(*b));
    let fourth = header.title_bytes[3];
    BY_TITLE
        .iter()
        .find(|(hash, letter, _)| *hash == sum && (*letter == 0 || *letter == fourth))
        .map_or(DEFAULT, |(_, _, p)| *p)
}

